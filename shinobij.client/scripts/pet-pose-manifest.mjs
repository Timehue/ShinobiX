import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const poseGroups = {
    POSED_PET_IDS: ['idle', 'attack', 'hurt', 'cast'],
    POSED_MOVE_IDS: ['windup', 'lunge', 'impact', 'recover'],
    POSED_RUN_IDS: ['run-a', 'run-b'],
};

export function petPoseMembership(filenames) {
    const files = new Set(filenames);
    return Object.fromEntries(Object.entries(poseGroups).map(([name, frames]) => {
        const suffix = `-${frames[0]}.webp`;
        const ids = [...files].filter(file => file.endsWith(suffix))
            .map(file => file.slice(0, -suffix.length))
            .filter(id => frames.every(frame => files.has(`${id}-${frame}.webp`)))
            .sort();
        return [name, ids];
    }));
}

function compactMembership(ids) {
    const ranges = [];
    const extras = [];
    const remaining = new Set(ids);
    for (const prefix of ['standard', 'rare', 'legendary', 'mythic']) {
        const numbered = ids.filter(id => new RegExp(`^${prefix}-\\d+$`).test(id));
        const numbers = numbered.map(id => Number(id.slice(prefix.length + 1))).sort((a, b) => a - b);
        if (numbers.length && numbers.every((number, index) => number === index)
            && numbered.every(id => id === `${prefix}-${Number(id.slice(prefix.length + 1))}`)) {
            ranges.push([prefix, numbers.length]);
            for (const id of numbered) remaining.delete(id);
        }
    }
    extras.push(...remaining);
    return { ranges, extras };
}

export function petPoseManifestTs(memberships) {
    const groups = [];
    const exports = Object.keys(poseGroups).map(name => {
        const ids = memberships[name];
        let index = groups.findIndex(group => JSON.stringify(group.ids) === JSON.stringify(ids));
        if (index < 0) {
            index = groups.length;
            groups.push({ ids, ...compactMembership(ids) });
        }
        return `export const ${name}: ReadonlySet<string> = new Set(ids${index});`;
    });
    return '// Generated by finalize-pet-poses.mjs / slice-all-move-frames.mjs. Do not edit.\n'
        + '// Each export owns a separate Set; shared input arrays preserve membership and insertion order.\n'
        + 'const rosterIds = (ranges: readonly (readonly [string, number])[], extras: readonly string[]): string[] => [\n'
        + '    ...ranges.flatMap(([prefix, count]) => Array.from({ length: count }, (_, index) => `${prefix}-${index}`)),\n'
        + '    ...extras,\n'
        + '].sort();\n'
        + groups.map((group, index) => `const ids${index} = rosterIds(${JSON.stringify(group.ranges)}, ${JSON.stringify(group.extras)});`).join('\n')
        + '\n' + exports.join('\n') + '\n';
}

export function syncPetPoseManifest(clientRoot, { checkOnly = false } = {}) {
    const memberships = petPoseMembership(readdirSync(join(clientRoot, 'public', 'pet-poses')));
    const manifest = join(clientRoot, 'src', 'assets', 'coliseum', 'pet-poses-manifest.ts');
    const source = petPoseManifestTs(memberships);
    if (checkOnly) {
        if (readFileSync(manifest, 'utf8').replaceAll('\r\n', '\n') !== source) throw new Error('Pet pose membership manifest is stale');
    } else {
        writeFileSync(manifest, source);
    }
    return memberships;
}
