"""Extract the reviewed companion illustrations as transparent board sprites.

Offline authoring only. Requires Pillow, NumPy, ONNX Runtime and the
BiRefNet-general-bb_swin_v1_tiny-epoch_232.onnx weights from the rembg release.
Run with the path to the weights as the sole argument.
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import onnxruntime as ort
from PIL import Image


CLIENT = Path(__file__).resolve().parents[1]
PORTRAITS = CLIENT / "art-source/pet-portrait-refresh"
PUBLIC = CLIENT / "public"
MODEL_SHA256 = "5600024376f572a557870a5eb0afb1e5961636bef4e1e22132025467d0f03333"
KINDS = {"avian": "flying", "biped": "humanoid", "quadruped": "quadruped", "heavy": "quadruped", "serpentine": "serpentine"}


# Native pose direction in the reviewed source illustrations.
LEFT_FACING = {
    "starter": {"earth", "earth-l", "earth-r", "fire", "lightning-r", "water", "water-r", "wind-l"},
    "standard": {2, 6, 10, 11, 12, 17, 18, 19, 28, 33, 38, 44, 45, 48},
    "rare": {3, 7, 12, 14, 15, 17, 28, 30, 33, 38, 40},
    "legendary": {1, 3, 10, 23, 29},
    "mythic": {2, 8, 9, 10, 11, 12, 13, 14},
}


def sprite_kind(species, roster):
    if species.startswith("starter-"):
        element = species.split("-")[1]
        if element == "earth" and species == "starter-earth":
            return "humanoid"
        return {"wind": "flying", "water": "serpentine"}.get(element, "quadruped")
    return KINDS[roster[species]["profile"]]


def cutout(session, portrait):
    sample = portrait.resize((1024, 1024), Image.Resampling.LANCZOS)
    rgb = np.asarray(sample, dtype=np.float32) / 255
    mean = np.array([.485, .456, .406], np.float32)
    std = np.array([.229, .224, .225], np.float32)
    tensor = ((rgb - mean) / std).transpose(2, 0, 1)[None].copy()
    logits = session.run(None, {"input_image": tensor})[0].squeeze()
    matte = 1 / (1 + np.exp(-np.clip(logits, -75, 75)))
    # Remove faint scenic pixels while keeping the antialiased fur and feather edges.
    alpha = np.uint8(np.clip((matte - .025) / .95, 0, 1) * 255)
    mask = Image.fromarray(alpha).resize(portrait.size, Image.Resampling.LANCZOS)
    bounds = mask.point(lambda value: 255 if value > 8 else 0).getbbox()
    if not bounds:
        raise ValueError("Empty foreground")
    portrait.putalpha(mask)
    body = portrait.crop(bounds)
    body.thumbnail((192, 192), Image.Resampling.LANCZOS)
    sprite = Image.new("RGBA", (body.width + 4, body.height + 4))
    sprite.paste(body, (2, 2))
    return sprite


def write_index(portraits, roster):
    rows = {}
    for entry in portraits:
        species = entry["id"]
        family, suffix = species.split("-", 1)
        if family == "starter":
            element, _, stage = suffix.partition("-")
            row, index = "starter-" + element, ("", "r", "l").index(stage)
            left = suffix in LEFT_FACING["starter"]
        else:
            row, index = family, int(suffix)
            left = index in LEFT_FACING[family]
        code = sprite_kind(species, roster)[0]
        rows.setdefault(row, {})[index] = code if left else code.upper()
    packed = {row: "".join(values[i] for i in range(len(values))) for row, values in sorted(rows.items())}
    header = "// Generated by scripts/cutout-pet-summons.py. One type/direction code per form.\n"
    source = header + "export const PET_SUMMON_ROWS = " + json.dumps(packed, indent=4) + " as const;\n"
    (CLIENT / "src/generated/pet-summon-sprites.ts").write_text(source, encoding="utf8")


def main(weights):
    with weights.open("rb") as stream:
        if hashlib.file_digest(stream, "sha256").hexdigest() != MODEL_SHA256:
            raise ValueError("Unexpected foreground model")
    options = ort.SessionOptions()
    options.enable_mem_pattern = False
    options.intra_op_num_threads = 4
    providers = [p for p in ("CUDAExecutionProvider", "DmlExecutionProvider", "CPUExecutionProvider") if p in ort.get_available_providers()]
    session = ort.InferenceSession(str(weights), options, providers=providers)
    portraits = json.loads((PORTRAITS / "production.json").read_text(encoding="utf8"))["entries"]
    roster = json.loads((PUBLIC / "pet-models/roster-manifest.json").read_text(encoding="utf8"))["entries"]
    for entry in portraits:
        species = entry["id"]
        if entry["status"] != "reviewed":
            raise ValueError(f"Unreviewed portrait: {species}")
        kind = sprite_kind(species, roster)
        path = PUBLIC / "combat-actors/pets" / kind / f"{species}-guard.webp"
        path.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(PORTRAITS / entry["master"]) as master:
            sprite = cutout(session, master.convert("RGB"))
        sprite.save(path, quality=82, method=6)
        print(species, flush=True)
    write_index(portraits, roster)


if __name__ == "__main__":
    main(Path(sys.argv[1]))
