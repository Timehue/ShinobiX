async function authorPet(clientRoot, pet) {
    const source = parseGlb(await readFile(resolve(clientRoot, pet.input)), pet.id);
    const json = structuredClone(source.json);
    const nodeByName = new Map(json.nodes.map((node, index) => [node.name, index]));
    const chunks = [{ offset: 0, bytes: source.bin }];
    let byteLength = source.bin.byteLength;
    json.bufferViews ??= [];
    json.accessors ??= [];

    const addAccessor = (array, type, options = {}) => {
        const bytes = new Uint8Array(array.buffer, array.byteOffset, array.byteLength);
        const offset = align4(byteLength);
        chunks.push({ offset, bytes });
        json.bufferViews.push({ buffer: 0, byteOffset: offset, byteLength: bytes.byteLength });
        byteLength = offset + bytes.byteLength;
        const accessor = { bufferView: json.bufferViews.length - 1, componentType: 5126, count: array.length / (type === "VEC4" ? 4 : type === "VEC3" ? 3 : 1), type };
        if (options.min) accessor.min = options.min;
        if (options.max) accessor.max = options.max;
        json.accessors.push(accessor);
        return json.accessors.length - 1;
    };

    json.animations = [];
    for (const take of pet.bank()) {
        invariant(take.times.length >= 2, `${pet.id}/${take.name}: at least two keyframes required`);
        const input = addAccessor(new Float32Array(take.times), "SCALAR", { min: [take.times[0]], max: [take.times.at(-1)] });
        const samplers = [];
        const channels = [];
        for (const track of take.tracks) {
            const nodeIndex = nodeByName.get(track.node);
            invariant(nodeIndex !== undefined, `${pet.id}/${take.name}: missing bone ${track.node}`);
            invariant(track.values.length === take.times.length, `${pet.id}/${take.name}/${track.node}: keyframe count mismatch`);
            const node = json.nodes[nodeIndex];
            let values;
            let type;
            if (track.path === "rotation") {
                const bind = new THREE.Quaternion(...(node.rotation ?? [0, 0, 0, 1])).normalize();
                values = track.values.flatMap((euler) => bind.clone()
                    .multiply(new THREE.Quaternion().setFromEuler(new THREE.Euler(...euler, "XYZ")))
                    .normalize()
                    .toArray());
                type = "VEC4";
            } else {
                const bind = node.translation ?? [0, 0, 0];
                values = track.values.flatMap((delta) => bind.map((value, axis) => value + delta[axis]));
                type = "VEC3";
            }
            const output = addAccessor(new Float32Array(values), type);
            samplers.push({ input, output, interpolation: "LINEAR" });
            channels.push({ sampler: samplers.length - 1, target: { node: nodeIndex, path: track.path } });
        }
        json.animations.push({ name: take.name, samplers, channels });
    }

    invariant(json.animations.length === 8, `${pet.id}: expected eight authored clips`);
    json.asset = { ...json.asset, generator: `Shinobi Journey Showdown ${pet.id} Animation Bank v2` };
    json.extras = { ...(json.extras ?? {}), showdownAnimationBank: "20260820-species-v2", animationAuthoring: "species-directed-keyframes" };
    json.buffers = [{ byteLength: align4(byteLength) }];
    const binary = new Uint8Array(align4(byteLength));
    for (const chunk of chunks) binary.set(chunk.bytes, chunk.offset);

    const outputDirectory = resolve(clientRoot, "public/pet-models/showdown-v2");
    await mkdir(outputDirectory, { recursive: true });
    const outputPath = resolve(outputDirectory, `${pet.id}.glb`);
    const encoded = encodeGlb(json, binary);
    await writeFile(outputPath, encoded);
    return { id: pet.id, outputPath, bytes: encoded.byteLength, clips: json.animations.map((animation) => animation.name) };
}

