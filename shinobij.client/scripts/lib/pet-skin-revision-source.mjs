/** Pool identical cache-revision strings without changing any identity/value. */
export function petSkinRevisionSource(revisions) {
    const values = [...new Set(Object.values(revisions))];
    const names = new Map(values.map((value, i) => [value, `SKIN_REVISION_${i}`]));
    const constants = values.map(value => `const ${names.get(value)} = ${JSON.stringify(value)};`).join('\n');
    const entries = Object.entries(revisions).map(([id, revision]) => `    ${JSON.stringify(id)}: ${names.get(revision)}`).join(',\n');
    return `/* Generated by pet skin repair promotion tools. */\n${constants}\nexport const PET_SKIN_REPAIR_REVISIONS: Readonly<Record<string, string>> = {\n${entries}\n};\n`;
}
