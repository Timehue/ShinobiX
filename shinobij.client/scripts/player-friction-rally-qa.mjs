import { chromium, expect as baseExpect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const base = process.env.SUNSCAR_QA_URL || 'http://127.0.0.1:5199';
const out = new URL('../../.tmp/player-friction-rally/', import.meta.url);
await mkdir(out, { recursive: true });
const expect = baseExpect.configure({ timeout: 60_000 });
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const report = { errors: [], checks: [] };
const rendererOnly = process.env.SUNSCAR_QA_RENDERER_ONLY === '1';
const shot = async (page, name) => page.screenshot({ path: fileURLToPath(new URL(name + '.png', out)) });
let page;
try {
    if (!rendererOnly) {
    const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, reducedMotion: 'reduce' });
    page = await context.newPage(); page.setDefaultTimeout(60_000);
    page.on('pageerror', error => report.errors.push(error.message));
    await page.addInitScript(() => { localStorage.setItem('petRally.render.v1', 'economy'); });
    await page.request.post(base + '/__qa/reset', { data: { rippleSeal: true, expiredReady: true } });
    const session = await page.request.get(base + '/__qa/session').then(r => r.json());
    const headers = { 'x-player-name': session.name, 'x-player-token': session.token };
    const saved = async () => page.request.get(base + '/api/festival/rally?playerName=' + session.name, { headers }).then(r => r.json());
    const expired = await saved();
    assert.notEqual(expired.progress.current.day, expired.daily.day);
    await page.goto(base + '/sunscar-modes-qa.html');
    await expect(page.locator('.sunscar-daily-ledger')).toContainText('Entry available');
    await page.locator('.sunscar-attraction-rally button').click();
    await expect(page.locator('.sunscar-status-pills')).toContainText('Daily Grand Prix available');
    const replacement = page.locator('.rally-pet-list button').first();
    await expect(replacement).toBeEnabled();
    await replacement.click();
    await expect(page.locator('.rally-pet-list button.selected')).not.toContainText('Ripple Seal');
    await page.getByRole('button', { name: 'Prepare Grand Prix' }).click();
    await expect(page.getByRole('button', { name: 'Ready to race' })).toBeEnabled();
    const refreshed = await saved();
    assert.notEqual(refreshed.progress.current.id, expired.progress.current.id);
    assert.equal(refreshed.progress.current.day, refreshed.daily.day);
    assert.notEqual(refreshed.progress.current.pet.id, expired.progress.current.pet.id);
    await shot(page, 'expired-ready-reprepared');
    await page.getByRole('button', { name: 'Ready to race' }).click();
    await page.waitForFunction(() => window.sunscarRallyQa?.state.tick > 30);
    assert.equal((await saved()).progress.current.status, 'racing');
    report.checks.push('prior-day unstarted reservation allows another companion, fresh prepare and real authoritative begin');
    await page.request.post(base + '/__qa/reset', { data: { rippleSeal: true } });
    const initial = await saved();
    assert.equal(initial.progress.current.status, 'ready');
    assert.equal(initial.progress.current.pet.templateId, 'starter-water');
    assert.equal(initial.preview.trackId, 'scorpions-spine');
    const runId = initial.progress.current.id;
    let prepares = 0;
    page.on('request', req => { if (req.url().endsWith('/api/festival/rally') && req.method() === 'POST' && req.postDataJSON()?.action === 'prepare') prepares++; });
    await page.goto(base + '/sunscar-modes-qa.html');
    await expect(page.locator('.sunscar-daily-ledger')).toContainText('In progress');
    await page.locator('.sunscar-attraction-rally button').click();
    await expect(page.locator('.sunscar-status-pills')).toContainText('Grand Prix in progress');
    await expect(page.locator('.rally-pet-list button.selected')).toContainText('Ripple Seal');
    await page.getByRole('button', { name: 'Resume Grand Prix' }).click();
    await expect(page.getByRole('button', { name: 'Ready to race' })).toBeEnabled();
    await shot(page, 'saved-ready-desktop');
    await page.getByRole('button', { name: 'Ready to race' }).click();
    await page.waitForFunction(() => window.sunscarRallyQa?.state.tick > 60);
    assert.equal((await saved()).progress.current.id, runId);
    assert.equal(prepares, 0, 'resuming a ready run must never prepare a replacement');
    await page.getByRole('button', { name: 'Pause race' }).click();
    await page.waitForFunction(() => !!window.sunscarRallyQa?.state);
    const paused = await page.evaluate(() => window.sunscarRallyQa.state.tick);
    await page.waitForTimeout(600);
    assert.equal(await page.evaluate(() => window.sunscarRallyQa.state.tick), paused);
    await page.getByRole('button', { name: 'Continue race' }).click();
    await page.waitForFunction(tick => window.sunscarRallyQa?.state.tick > tick + 30, paused);
    await page.getByRole('button', { name: 'Pause race' }).click();
    await page.getByRole('button', { name: 'Save & return' }).click();
    const checkpoint = await saved();
    assert.ok(checkpoint.progress.current.race.tick > 0);
    await page.reload();
    await page.locator('.sunscar-attraction-rally button').click();
    await page.getByRole('button', { name: 'Resume Grand Prix' }).click();
    await expect(page.getByRole('button', { name: 'Resume from checkpoint' })).toBeEnabled();
    await page.setViewportSize({ width: 360, height: 640 });
    await shot(page, 'checkpoint-mobile');
    await page.getByRole('button', { name: 'Resume from checkpoint' }).click();
    await page.waitForFunction(tick => window.sunscarRallyQa?.state.tick > tick + 30, checkpoint.progress.current.race.tick);
    report.checks.push('saved ready Ripple Seal Scorpion run resumes without prepare', 'official start advances', 'pause freezes and resume advances', 'saved checkpoint survives reload');
    for (let index = 0; index < 3; index++) {
        await expect(page.locator('.rally-results')).toBeVisible({ timeout: 150_000 });
        const confirmed = await saved();
        assert.equal(confirmed.progress.current.results.length, index + 1);
        await shot(page, 'race-' + (index + 1) + '-confirmed');
        if (index < 2) {
            await page.getByRole('button', { name: /^Next race/ }).click();
            await page.getByRole('button', { name: 'Ready to race' }).click();
        }
    }
    const final = await saved();
    assert.equal(final.progress.current.status, 'complete');
    assert.ok(final.progress.current.reward.ryo > 0);
    report.reward = final.progress.current.reward;
    report.checks.push('all three races confirmed by production checkpoints and reward recorded');
    await page.getByRole('button', { name: 'Return to the race desk' }).click();
    await expect(page.getByRole('button', { name: 'Return tomorrow' })).toBeDisabled();
    await page.reload();
    await expect(page.locator('.sunscar-daily-ledger')).toContainText('Complete for today');
    await page.locator('.sunscar-attraction-rally button').click();
    await expect(page.locator('.sunscar-status-pills')).toContainText('Grand Prix complete today');
    const stable = await saved();
    assert.equal(stable.progress.championships, final.progress.championships);
    report.checks.push('hub and desk agree after completion and reload; no duplicate reward');
    await context.close();
    }
    const high = await browser.newContext({ viewport: { width: 1366, height: 768 }, reducedMotion: 'no-preference' });
    page = await high.newPage(); page.setDefaultTimeout(60_000);
    page.on('pageerror', error => report.errors.push(error.message));
    await page.addInitScript(() => {
        localStorage.setItem('petRally.render.v1', '3d');
        Object.defineProperty(navigator, 'hardwareConcurrency', { get: () => 16 });
        Object.defineProperty(navigator, 'deviceMemory', { get: () => 8 });
    });
    await page.goto(base + '/sunscar-modes-qa.html');
    await page.locator('.sunscar-attraction-rally button').click();
    await page.locator('.rally-pet-list button').filter({ hasText: 'Ripple Seal' }).click();
    await page.getByRole('button', { name: 'Practice selected course' }).click();
    await expect(page.getByRole('button', { name: 'Ready to race' })).toBeEnabled();
    await page.waitForFunction(() => ['full', 'light'].includes(window.sunscarRallyQa?.quality));
    await shot(page, '3d-ready');
    await page.getByRole('button', { name: 'Ready to race' }).click();
    await page.waitForFunction(() => window.sunscarRallyQa?.state.tick > 30);
    await shot(page, '3d-moving');
    report.checks.push('normal 3D Ripple Seal practice starts and advances in local Chromium WebGL');
    await page.getByRole('button', { name: 'Pause race' }).click();
    const pausedProgress = await page.getByRole('progressbar', { name: 'Race progress' }).getAttribute('value');
    await page.waitForTimeout(600);
    assert.equal(await page.getByRole('progressbar', { name: 'Race progress' }).getAttribute('value'), pausedProgress);
    const paused3d = await page.evaluate(() => window.sunscarRallyQa.state.tick);
    await page.getByRole('button', { name: 'Continue race' }).click();
    await page.waitForFunction(tick => window.sunscarRallyQa?.state.tick > tick + 30, paused3d);
    await page.getByRole('button', { name: 'Pause race' }).click();
    await page.getByRole('combobox', { name: 'Race graphics' }).selectOption('economy');
    await page.waitForFunction(() => window.sunscarRallyQa?.quality === 'economy');
    const fallbackTick = await page.evaluate(() => window.sunscarRallyQa.state.tick);
    await page.getByRole('button', { name: 'Continue race' }).click();
    await page.waitForFunction(tick => window.sunscarRallyQa?.state.tick > tick + 30, fallbackTick);
    report.checks.push('3D pause/resume and in-race battery-saver change preserve the clock');
    assert.deepEqual(report.errors, []);
} catch (error) {
    report.failure = error.stack;
    if (page && !page.isClosed()) await shot(page, 'failure').catch(() => {});
    throw error;
} finally {
    await writeFile(new URL(rendererOnly ? 'renderer-report.json' : 'report.json', out), JSON.stringify(report, null, 2));
    await browser.close();
}
console.log(JSON.stringify(report, null, 2));
