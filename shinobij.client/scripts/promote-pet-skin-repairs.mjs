import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { resolve, relative, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { runtimePetModels } from './lib/pet-runtime-audit.mjs';
const root = resolve(import.meta.dirname, '..'), modelRoot = resolve(root, 'public/pet-models');
const candidates = resolve(root, '.tmp/pet-skin-candidates'), backup = resolve(root, '.tmp/pet-quality-originals');
const audit = JSON.parse(await readFile(resolve(root, '.tmp/pet-animation-audit/all-pet-final-candidate-motion-audit.json')));
if (audit.summary.auditedModels !== 161 || audit.failures.length || audit.deformationWarnings.length) throw Error('Every candidate must pass the complete pose audit before promotion.');
const manifestPath = resolve(modelRoot, 'roster-manifest.json'), manifest = JSON.parse(await readFile(manifestPath));
const revisions = {}, receipts = [];
for (const row of new Map(runtimePetModels.map(row => [row.path, row])).values()) {
    const path = relative(modelRoot, row.path), candidate = resolve(candidates, path);
    const bytes = await readFile(candidate), json = JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)));
    if (!json.extras?.skinSeamRepair) continue;
    let original = await readFile(row.path);
    const currentHash = createHash('sha256').update(original).digest('hex');
    const candidateHash = createHash('sha256').update(bytes).digest('hex');
    const originalBackup = resolve(backup, path);
    if (currentHash === candidateHash) original = await readFile(originalBackup);
    else {
        if (currentHash !== json.extras.skinSeamRepair.sourceSha256) throw Error(`Source changed after candidate creation: ${path}`);
        await mkdir(dirname(originalBackup), { recursive: true }); await copyFile(row.path, originalBackup);
        await copyFile(candidate, row.path);
    }
    revisions[row.model.visualId] = '20261012-connected-weight-v1';
    const sha256 = createHash('sha256').update(bytes).digest('hex').toUpperCase();
    if (path.replaceAll('\\', '/').startsWith('roster/') && manifest.entries[row.model.visualId]) {
        const entry = manifest.entries[row.model.visualId]; entry.sha256 = sha256;
        if (entry.validation) entry.validation.bytes = bytes.length;
        entry.skinSeamRepair = json.extras.skinSeamRepair;
    }
    receipts.push({ id: row.model.visualId, path, sha256, bytes: bytes.length, sourceBytes: original.length, repair: json.extras.skinSeamRepair });
}
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
await writeFile(resolve(root, 'src/generated/pet-skin-repair-revisions.ts'), `/* Generated by scripts/promote-pet-skin-repairs.mjs. */\nexport const PET_SKIN_REPAIR_REVISIONS: Readonly<Record<string, string>> = Object.fromEntries(\n    ${JSON.stringify(Object.keys(revisions))}.map(id => [id, '20261012-connected-weight-v1']),\n);\n`);
await writeFile(resolve(backup, 'promotion-receipt.json'), JSON.stringify(receipts, null, 2));
console.log(JSON.stringify({ promoted: receipts.length, addedBytes: receipts.reduce((sum, r) => sum + r.bytes - r.sourceBytes, 0), backups: backup }));
