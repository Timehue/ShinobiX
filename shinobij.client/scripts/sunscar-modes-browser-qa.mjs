import { chromium } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:5199';
const out = new URL('../../.tmp/sunscar-visual-qa/', import.meta.url);
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [], audits = [], metrics = [];
const capture = async (page, name) => { await page.screenshot({ path: fileURLToPath(new URL(name + '.png', out)), fullPage: true }); };
try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, reducedMotion: 'reduce' });
    const page = await context.newPage(); page.setDefaultTimeout(20_000);
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error' && !m.text().includes('favicon')) errors.push(m.text()); });
    await page.request.post(base + '/__qa/reset');
    await page.goto(base + '/sunscar-modes-qa.html');
    await page.getByRole('button', { name: 'Visit the race grounds' }).waitFor();
    await capture(page, 'hub-desktop');
    audits.push({ screen: 'hub', violations: (await new AxeBuilder({ page }).include('.sunscar-mode').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations });
    await page.getByRole('button', { name: 'Visit the race grounds' }).click();
    await page.getByRole('button', { name: 'Practice selected course' }).waitFor();
    await capture(page, 'rally-lobby-desktop');
    await page.getByRole('button', { name: 'Practice selected course' }).click();
    await page.getByRole('button', { name: 'Ready to race' }).waitFor({ timeout: 90_000 });
    await page.getByRole('button', { name: 'Ready to race' }).click({ timeout: 90_000 });
    await page.getByRole('button', { name: 'Pause race' }).waitFor();
    await page.waitForTimeout(6000);
    await capture(page, 'rally-racing-desktop');
    await page.keyboard.press('ArrowLeft'); await page.keyboard.press('Space');
    await page.keyboard.down('Shift'); await page.waitForTimeout(700); await page.keyboard.up('Shift');
    await page.keyboard.press('KeyE');
    await page.waitForTimeout(800);
    await capture(page, 'rally-technique');
    await page.getByRole('button', { name: 'Pause race' }).click();
    await capture(page, 'rally-pause');
    await page.getByRole('button', { name: 'Save & return' }).click();
    await page.getByRole('button', { name: /Festival$/ }).click();
    await page.getByRole('button', { name: 'Read today’s contracts' }).click();
    await page.getByRole('button', { name: 'Accept contract & depart' }).waitFor();
    await capture(page, 'caravan-board-desktop');
    await page.getByRole('button', { name: 'Accept contract & depart' }).click();
    await page.getByRole('heading', { name: 'Choose the next road' }).waitFor();
    await capture(page, 'caravan-map-desktop');
    await page.locator('.caravan-route-options button').first().click();
    await page.getByRole('button', { name: 'Travel to this stop' }).click();
    await page.locator('.caravan-choices button').first().waitFor();
    await capture(page, 'caravan-event-desktop');
    await page.locator('.caravan-choices button:enabled').first().click();
    await page.waitForTimeout(250);
    audits.push({ screen: 'caravan', violations: (await new AxeBuilder({ page }).include('.sunscar-mode').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations });
    for (const width of [390, 320]) {
        await page.setViewportSize({ width, height: 844 });
        await capture(page, 'caravan-mobile-' + width);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Caravan must fit viewport ' + width);
    }
    metrics.push(await page.evaluate(() => ({ memory: performance.memory?.usedJSHeapSize, requests: performance.getEntriesByType('resource').length })));
    await writeFile(new URL('report.json', out), JSON.stringify({ errors, audits, metrics }, null, 2));
    assert.deepEqual(errors, [], 'No browser runtime errors');
    console.log(JSON.stringify({ errors, violations: audits.map(a => ({ screen: a.screen, violations: a.violations.map(v => ({ id: v.id, nodes: v.nodes.length })) })), metrics }));
} finally { await browser.close(); }
