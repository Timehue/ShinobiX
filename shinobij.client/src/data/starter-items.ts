function legendarySetBonuses(effect: LegendarySetEffect, value: number, offense = 30): GameItem["bonuses"] {
    return {
        ninjutsuOffense: offense,
        taijutsuOffense: offense,
        bukijutsuOffense: offense,
        genjutsuOffense: offense,
        ninjutsuDefense: 30,
        taijutsuDefense: 30,
        bukijutsuDefense: 30,
        genjutsuDefense: 30,
        [effect]: value,
    };
}

