import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
import registry from './_chronicle-art-registry.cjs';
import { CHRONICLE_PAINTED_ART, CHRONICLE_PAINTED_FIGURES } from '../shared/chronicle-painted-art.ts';

const hash = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
test('packed art registries preserve every admitted URL, insertion order and frozen public record', () => {
  // Captured from the full literal registries before packing, not generated by
  // the production helper. Saved overrides and legacy redirects use these IDs.
  assert.equal(Object.keys(CHRONICLE_PAINTED_ART).length, 404);
  assert.equal(hash(CHRONICLE_PAINTED_ART), 'bbce7607761c0e1ef42b7b6d3b1acd2551f07304677b6614bd0868677d80ea70');
  assert.equal(Object.keys(CHRONICLE_PAINTED_FIGURES).length, 150);
  assert.equal(hash(CHRONICLE_PAINTED_FIGURES), '7c662e09b392592cbd8869cfbbf94a83988311bd215e61ee43731d7fca66b165');
  for (const value of [CHRONICLE_PAINTED_ART, CHRONICLE_PAINTED_FIGURES]) {
    assert.equal(Object.getPrototypeOf(value), Object.prototype);
    assert(Object.isFrozen(value));
  }
  assert(!Object.isFrozen(CHRONICLE_PAINTED_FIGURES['tc-01']));
});

test('production registry generation reproduces the exact packaged manifest', () => {
  const manifest = JSON.parse(readFileSync(new URL('../shinobij.client/art-source/chronicle-refresh/manifest.json', import.meta.url), 'utf8'));
  const packaged = manifest.cards.filter(row => row.status === 'packaged');
  const art = Object.fromEntries(packaged.map(row => [row.id, row.runtimePath]));
  const figures = Object.fromEntries(packaged.filter(row => row.figures?.front && row.figures?.back).map(row => [row.id, {front: row.figures.front.runtimePath, back: row.figures.back.runtimePath}]));
  assert.deepEqual(CHRONICLE_PAINTED_ART, art);
  assert.deepEqual(CHRONICLE_PAINTED_FIGURES, figures);
  assert.equal(readFileSync(new URL('../shared/chronicle-painted-art.ts', import.meta.url), 'utf8').replaceAll('\r\n', '\n'), registry.chronicleArtRegistrySource(art, figures));
});

test('future unusual paths and an empty registry retain exact literal values and order', () => {
  for (const [art, figures] of [[{}, {}], [
    {'tc-01': '/chronicle/cards/tc-01-painted-v2.webp', 'custom card': '/new-path/v3.webp'},
    {'tc-01': {front: '/different-front.webp', back: '/different-back.webp'}},
  ]]) {
    const source = registry.chronicleArtRegistrySource(art, figures);
    const exports = {};
    runInNewContext(ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText, {exports});
    assert.equal(JSON.stringify(exports.CHRONICLE_PAINTED_ART), JSON.stringify(art));
    assert.equal(JSON.stringify(exports.CHRONICLE_PAINTED_FIGURES), JSON.stringify(figures));
  }
});
