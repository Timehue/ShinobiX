#!/usr/bin/env bash
# Refresh the `railway-deploy` branch from a commit that already passed CI.
#
# WHY THIS EXISTS. Railway builds from a snapshot of the whole repository at the
# deployed commit. Our tree is about 10.5 GB, almost all of it review evidence
# under docs/ (docs/screenshots alone is 8.4 GB). Railway's builder could not
# fetch a snapshot that size and every build failed with "failed to fetch
# snapshot" (2026-10-24..26). The Docker image never contained those folders
# (.dockerignore excludes them), so the deploy branch is the same commit with
# the same folders removed: identical image, roughly a tenth of the snapshot.
#
# The branch is rebuilt from git objects only. Nothing is checked out and no
# file contents are downloaded, so this runs against a blob:none shallow fetch.
#
# Usage: refresh-railway-deploy-branch.sh <commit-sha> [target-branch]
#
# The folders dropped here must stay in step with .dockerignore. A folder the
# image needs must NOT be listed: .github stays so the commit never touches a
# workflow file (a GITHUB_TOKEN push is refused if it does).
set -euo pipefail

SHA="${1:?usage: refresh-railway-deploy-branch.sh <commit-sha> [target-branch]}"
TARGET="${2:-railway-deploy}"

# Mirrors .dockerignore: none of these end up in the image.
DROP=(docs release-audit mobile android shinobij.client/art-source shinobij.client/art-references .ci-evidence)
# The build verifies portrait hashes against this manifest, so it ships.
KEEP='shinobij.client/art-source/pet-portrait-refresh/production.json'

INDEX_FILE="$(mktemp -u)"
PATH_LIST="$(mktemp)"
export GIT_INDEX_FILE="$INDEX_FILE"
trap 'rm -f "$INDEX_FILE" "$PATH_LIST"' EXIT

git read-tree "$SHA"

for dir in "${DROP[@]}"; do
  git ls-files -z -- "$dir" | { grep -zvxF "$KEEP" || true; } > "$PATH_LIST"
  # A folder that does not exist at this commit yields an empty list, and
  # `git rm` with no pathspec is an error, so skip it.
  if [ -s "$PATH_LIST" ]; then
    # --sparse: a sparse checkout (as in a developer clone) would otherwise
    # refuse to remove index entries that sit outside its cone.
    git rm --cached --sparse -q --pathspec-from-file="$PATH_LIST" --pathspec-file-nul
  fi
done

TREE="$(git write-tree)"

# A tree without these cannot build, whatever else is true. Refuse to publish it.
for required in Dockerfile railway.json package.json server.ts api shinobij.client/src; do
  if [ -z "$(git ls-tree "$TREE" -- "$required")" ]; then
    echo "refusing to publish: $required is missing from the lean tree" >&2
    exit 1
  fi
done

COMMIT="$(git commit-tree "$TREE" -p "$SHA" -m "Railway deploy branch: $SHA minus folders the Docker image already excludes

Same code as $SHA. docs/, release-audit, mobile, android and the art sources
are in .dockerignore, so the built image is unchanged; the source snapshot
Railway fetches shrinks from about 10 GB to about 1 GB.

Generated by scripts/refresh-railway-deploy-branch.sh. Do not edit by hand.")"

# The branch is rebuilt on top of whatever main commit just passed CI, so it is
# not a fast-forward of its previous tip. Forcing is the point.
git push --force origin "$COMMIT:refs/heads/$TARGET"

echo "branch=$TARGET commit=$COMMIT source=$SHA"
