import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rawPetPool } from '../shinobij.client/src/data/pet-pool.ts';
import { STARTER_PETS } from '../shinobij.client/src/data/starter-pets.ts';
import { STARTER_EVOLUTIONS } from '../shinobij.client/src/data/pet-evolutions.ts';
import { balanceBuiltInPetTemplate } from '../shinobij.client/src/lib/pet-balance.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'api', 'pet', '_catalog.ts');
export function buildPetCatalog() {
    const normal = rawPetPool.map(balanceBuiltInPetTemplate);
    // Starter payloads are digest-validated byte-for-byte by api/pet/_starter.
    // Decorate the SERVER catalog copies instead of mutating the signed client
    // objects. Evolved starter forms are editor/visual templates, not normal
    // acquisition results, and remain protected as well.
    const protectedStarters = [
        ...STARTER_PETS.map(({ pet }) => pet),
        ...STARTER_EVOLUTIONS,
    ].map((pet) => ({ ...pet, wildSpawnable: false, breedable: false }));
    return Object.fromEntries([...normal, ...protectedStarters].map((pet) => [pet.id, pet]));
}
function render(catalog) {
    return `/* GENERATED by scripts/pet-catalog-gen.mjs; do not edit. */\nexport const PET_CATALOG: Record<string, Record<string, unknown>> = ${JSON.stringify(catalog, null, 4)};\n`;
}
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
    const catalog = buildPetCatalog();
    writeFileSync(out, render(catalog), 'utf8');
    console.log(`Wrote ${Object.keys(catalog).length} pets to ${out}`);
}
