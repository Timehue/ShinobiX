/* Run with `node --import tsx scripts/chronicle-art-production.cjs <command>`.
 * This tool inventories, packages and audits built-in image-generation outputs;
 * it deliberately makes no provider requests and never marks queued art done.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const artBriefs = require('./chronicle-art-briefs.json');
const { CHRONICLE_CARD_CATALOG, CHRONICLE_TOKEN_CARDS, CHRONICLE_STARTER_CORE_IDS } = require('../shared/chronicle-duel.ts');
const { CHRONICLE_PAINTED_FIGURES } = require('../shared/chronicle-painted-art.ts');
const root = path.resolve(__dirname, '..');
const productionDir = path.join(root, 'shinobij.client/art-source/chronicle-refresh');
const publicDir = path.join(root, 'shinobij.client/public');
const manifestFile = path.join(productionDir, 'manifest.json');
const cards = [...CHRONICLE_CARD_CATALOG, ...CHRONICLE_TOKEN_CARDS];
const pilotNames = ['Cinder Ant', 'Snow Warden Pup', 'Galebound Witness', 'Gale Reversal', 'Frost Seal Guardian', 'Wandering Sage', 'Heaven-Shatter Drake', 'Forbidden Archive'];
// Several human cards use the mechanical "Beast" family. It is not an art
// brief: passing it to the image provider turned thieves and monks into foxes.
const humanIds=new Set([4,6,7,11,16,20,30,31,33,36,37,39,50,59,67,68,78,79,87,88,93,99,100,101,102,103,104,107,108,110,111,112,113,115,118,123,124,126,127,128,129,134,136,137,138,146,147,148].map(id=>`tc-${String(id).padStart(2,'0')}`));
const style = 'Premium hand-painted anime-fantasy collectible-card illustration. Rich painterly materials, crisp believable anatomy, restrained cinematic lighting, Japanese-inspired shinobi fantasy world, atmospheric background depth. Clear silhouette and readable subject at thumbnail size. No photographic look, no 3D render, no flat cartoon sticker outlines. Portrait 1024x1536; final crop is 768x1097. Main subject in the middle, defining features between 22% and 57% from top; quiet top 15% and bottom 28% for interface overlays. Illustration only: no lettering, no frame, no icons, no watermark, no holographic coating baked in.';
function hash(file) { return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'); }
function relative(file) { return path.relative(root, file).replaceAll('\\', '/'); }
function readManifest() { return JSON.parse(fs.readFileSync(manifestFile, 'utf8')); }
function saveManifest(data) { fs.writeFileSync(manifestFile, JSON.stringify(data, null, 2) + '\n'); }
function publishRegistry(data) {
  const art = Object.fromEntries(data.cards.filter(row => row.status === 'packaged').map(row => [row.id, row.runtimePath]));
  const figures = Object.fromEntries(data.cards.filter(row => row.status === 'packaged' && row.figures?.front && row.figures?.back).map(row => [row.id, { front: row.figures.front.runtimePath, back: row.figures.back.runtimePath }]));
  fs.writeFileSync(path.join(root, 'shared/chronicle-painted-art.ts'), '// Generated by scripts/chronicle-art-production.cjs from packaged, verified assets.\nexport const CHRONICLE_PAINTED_ART: Readonly<Record<string, string>> = Object.freeze(' + JSON.stringify(art, null, 2) + ');\n\nexport const CHRONICLE_PAINTED_FIGURES: Readonly<Record<string, { front: string; back: string }>> = Object.freeze(' + JSON.stringify(figures, null, 2) + ');\n');
}
function prompt(card) {
  const rarity = card.rarity === 'common' ? 'Grounded intimate scene, modest effects, excellent finish.' : card.rarity === 'rare' ? 'Rich environment, purposeful action, clear lighting.' : card.rarity === 'epic' ? 'Dramatic action composition, controlled magical effects.' : 'Signature awe-inspiring scene with exceptional material detail, tasteful gold accents and controlled elemental energy; leave rainbow foil to the interface.';
  const subject = card.cardClass === 'monster'
    ? `${humanIds.has(card.id)||card.id.startsWith('legacy-') ? 'A HUMAN shinobi character' : 'The actual named creature, character, spirit or construct'}: ${card.name}, associated with ${card.element}. Preserve the subject’s species, distinguishing costume and recognizable identity. ${humanIds.has(card.id)||card.id.startsWith('legacy-') ? 'Natural human face and hands; no animal head, muzzle, fur, paws or animal ears.' : 'Do not replace named animals or insects with human ninjas.'}`
    : `${card.cardClass === 'magic' ? card.magicType + ' Jutsu' : card.trapType + ' Snare'}: depict the action or effect as a readable story moment, not an emblem or a stock portrait. Effect: ${card.effectText}`;
  return `Use case: stylized-concept. Final card artwork for ${card.name}. ${style}\nSubject: ${subject}\nLore: ${card.lore}\n${card.rarity} rarity direction: ${rarity}${artBriefs[card.id] ? '\nSpecific art brief: '+artBriefs[card.id] : ''}\nCritical card-layout constraint: place the face and eyes, or the main identifying object, around 36 percent from the top (about y=550 in a 1024x1536 portrait). Keep the top 22 percent free of faces and crucial identity details. Do not squeeze the entire figure into the image if that pushes the head upward; the lower body may continue off the bottom. Preserve reference identity, not its old framing.`;
}
async function inventory() {
  fs.mkdirSync(productionDir, { recursive: true });
  const previous = fs.existsSync(manifestFile) ? readManifest() : { cards: [] };
  const data = { version: 2, provider: 'built-in image_gen', style, target: 'Replace every catalog card and token with a distinct, consistent illustration; matching front/back figures for cards that already have figures; legendary/mythic holographic presentation.', pilotNames, cards: cards.map(card => {
    const old = previous.cards.find(row => row.id === card.id);
    return { id: card.id, name: card.name, rarity: card.rarity, element: card.element ?? null, cardClass: card.cardClass, originalPath: old?.originalPath ?? card.image ?? null,
      runtimePath: `/chronicle/cards/${card.id}-painted-v2.webp`, smallPath: `/chronicle/cards/${card.id}-painted-v2-512.webp`,
      masterPath: `shinobij.client/art-source/chronicle-refresh/masters/${card.id}.png`,
      needsFigures: Boolean(old?.needsFigures || CHRONICLE_PAINTED_FIGURES[card.id] || fs.existsSync(path.join(publicDir, 'chronicle/figures', `${card.id}.webp`))),
      figurePrompts: {
        front: `Use case: background-extraction. Asset type: transparent duel-board creature sprite. Isolate the main ${card.name} from the supplied NEW card illustration. Preserve its exact species, colors, materials, costume and painted finish. Show the single subject’s entire body including feet, tail, wings or antennae, viewed frontally, facing the viewer, centered with a clear silhouette and no clipped extremities. Reconstruct obscured parts consistently when needed. Remove ALL scenery, lettering, magic circles, floor and cast shadow. Genuine transparent background, not a checkerboard painting. No frame, text, icons, duplicate creature or unrelated human. The only subject is ${card.name}.`,
        back: `Use case: identity-preserve. Asset type: transparent duel-board back-view creature sprite. Paint the exact same ${card.name} from the supplied NEW front sprite, now seen directly FROM BEHIND facing away from the viewer. Preserve exact species, anatomy, colors, costume, materials, proportions and painted finish. Show the entire body including feet, tail and wings, centered, grounded at bottom, no clipped extremities. One character only, full genuine transparent background. No scenery, floor, cast shadow, lettering, frame, icons or duplicate creature. This is a matching back view, not another frontal portrait.`
      },
      pilot: pilotNames.includes(card.name), starter: CHRONICLE_STARTER_CORE_IDS.includes(card.id),
      status: 'queued', prompt: old?.prompt ?? prompt(card), ...old,
      ...(old?.status !== 'packaged' && !old?.pilot && !old?.identityReference && !old?.pairedCreatureReference ? {
        prompt: prompt(card) + '\nInput image: visual STYLE reference only. Match the sophisticated brushwork, fine material texture and cinematic painted finish; create the named subject in its own distinct scene. Do not copy the reference character or composition.',
        styleReference: 'shinobij.client/art-source/chronicle-refresh/masters/story-wandering-sage.png'
      } : {}) };
  }) };
  saveManifest(data); publishRegistry(data);
  console.log(JSON.stringify({ cards: data.cards.length, pilot: data.cards.filter(r => r.pilot).map(r => ({ id:r.id, name:r.name })), figures: data.cards.filter(r => r.needsFigures).length }));
}
async function accept(id, source) {
  const data = readManifest();
  const row = data.cards.find(row => row.id === id);
  if (!row) throw Error(`Unknown card ${id}`);
  const meta = await sharp(source).metadata();
  if ((meta.width ?? 0) < 768 || (meta.height ?? 0) < 1097) throw Error('Master must be at least 768x1097; never upscale final artwork.');
  const master = path.join(root, row.masterPath);
  fs.mkdirSync(path.dirname(master), { recursive:true });
  if (path.resolve(source) !== master) await sharp(source).png().toFile(master);
  const full = path.join(publicDir, row.runtimePath);
  const small = path.join(publicDir, row.smallPath);
  await sharp(master).resize(768, 1097, { fit:'cover', position:'centre' }).webp({ quality:86, effort:6 }).toFile(full);
  await sharp(full).resize({ width:512 }).webp({ quality:80, effort:6 }).toFile(small);
  const newHash=hash(master);
  if(row.masterSha256!==newHash) {
    delete row.visualReview;
    delete row.figureVisualReview;
    if(row.figures){row.supersededFigures=row.figures;delete row.figures;}
  }
  row.status = 'packaged'; row.masterSha256 = newHash; row.runtimeSha256 = hash(full); row.smallSha256 = hash(small);
  delete row.reviewIssue;
  saveManifest(data); publishRegistry(data);
  console.log(JSON.stringify({ id, name:row.name, status:row.status, completed:data.cards.filter(r => r.status === 'packaged').length, total:data.cards.length }));
}
async function acceptFigure(id, direction, source) {
  if (!['front', 'back'].includes(direction)) throw Error('Figure direction must be front or back.');
  const data=readManifest(), row=data.cards.find(row=>row.id===id);
  if (!row?.needsFigures || row.status !== 'packaged') throw Error('Package the matching card illustration first.');
  const metadata=await sharp(source).metadata(), stats=await sharp(source).stats();
  if (!metadata.hasAlpha || stats.channels[3]?.min !== 0) throw Error('Figure must have genuine transparent pixels.');
  const master=path.join(productionDir,'masters',`${id}-${direction}.png`);
  await sharp(source).png().toFile(master);
  const runtimePath=`/chronicle/figures/${id}-painted-v2${direction === 'back' ? '-back' : ''}.webp`;
  const output=path.join(publicDir,runtimePath);
  await sharp(master).trim({threshold:8}).resize({width:640,height:640,fit:'inside',withoutEnlargement:true}).webp({quality:86,effort:6}).toFile(output);
  row.figures ??= {};
  row.figures[direction]={masterPath:relative(master),runtimePath,sha256:hash(output),masterSha256:hash(master),prompt:row.figurePrompts[direction],facing:direction === 'front' ? 'F' : 'back'};
  delete row.figureVisualReview;
  saveManifest(data);publishRegistry(data);
  console.log(JSON.stringify({id,direction,runtimePath,matchingPair:!!(row.figures.front && row.figures.back)}));
}
function reject(id, reason) {
  const data=readManifest(),row=data.cards.find(row=>row.id===id);
  if(!row||!reason)throw Error('Reject requires a known card and review reason.');
  if(row.status==='packaged'){
    const archived=`shinobij.client/art-source/chronicle-refresh/rejected/${id}-${row.masterSha256.slice(0,10)}.png`;
    fs.mkdirSync(path.dirname(path.join(root,archived)),{recursive:true});
    fs.copyFileSync(path.join(root,row.masterPath),path.join(root,archived));
    row.rejectedVariants??=[];row.rejectedVariants.push({masterPath:archived,prompt:row.prompt,reason});
  }
  row.status='needs-correction';row.reviewIssue=reason;
  delete row.visualReview;
  saveManifest(data);publishRegistry(data);
  console.log(JSON.stringify({id,status:row.status,reason}));
}
async function contacts(phase = 'original') {
  const data = readManifest();
  let rows = phase === 'pilot' ? data.cards.filter(r => r.pilot && r.status === 'packaged') : phase === 'new' ? data.cards.filter(r => r.status === 'packaged') : data.cards;
  const idsIndex=process.argv.indexOf('--ids'), tagIndex=process.argv.indexOf('--tag');
  if(idsIndex>=0){const ids=new Set(process.argv[idsIndex+1].split(','));rows=rows.filter(row=>ids.has(row.id));}
  const tag=tagIndex>=0 ? process.argv[tagIndex+1].replace(/[^a-z0-9-]/gi,'') : phase;
  fs.mkdirSync(path.join(productionDir, 'review'), { recursive:true });
  for (let start=0; start<rows.length; start+=30) {
    const page=rows.slice(start,start+30), width=1200, cellW=200, cellH=285;
    const layers=[];
    for (let i=0;i<page.length;i++) {
      const row=page[i], source=path.join(publicDir, phase === 'original' ? row.originalPath : row.runtimePath);
      if (!fs.existsSync(source)) continue;
      const x=(i%6)*cellW,y=Math.floor(i/6)*cellH;
      layers.push({ input:await sharp(source).resize(190,250,{fit:'cover'}).png().toBuffer(),left:x+5,top:y });
      const label = `${row.id} ${row.name}`.replaceAll('&','&amp;').replaceAll('<','&lt;');
      layers.push({input:Buffer.from(`<svg width="200" height="35"><rect width="200" height="35" fill="#0b121c"/><text x="5" y="13" fill="white" font-size="9" font-family="Arial">${label.slice(0,37)}</text><text x="5" y="27" fill="#c2b69f" font-size="10" font-family="Arial">${row.rarity}</text></svg>`),left:x,top:y+250});
    }
    const output=path.join(productionDir,'review',`${tag}-${String(start/30+1).padStart(2,'0')}.webp`);
    await sharp({create:{width,height:Math.ceil(page.length/6)*cellH,channels:3,background:'#0b121c'}}).composite(layers).webp({quality:88}).toFile(output);
    console.log(relative(output));
  }
}
async function audit() {
  const data=readManifest(), failures=[];
  const digests=new Map();
  for(const row of data.cards) {
    if(row.status !== 'packaged') { failures.push(`${row.id}: artwork pending`); continue; }
    if(row.visualReview?.result!=='accepted'||!row.runtimeSha256||row.visualReview.runtimeSha256!==row.runtimeSha256)failures.push(`${row.id}: visual review pending`);
    for(const [key,digest] of [['masterPath','masterSha256'],['runtimePath','runtimeSha256'],['smallPath','smallSha256']]) {
      const file=key === 'masterPath' ? path.join(root,row[key]) : path.join(publicDir,row[key]);
      if(!fs.existsSync(file) || hash(file)!==row[digest]) failures.push(`${row.id}: invalid ${key}`);
      else await sharp(file).resize(1,1).toBuffer();
    }
    const full=path.join(publicDir,row.runtimePath), small=path.join(publicDir,row.smallPath);
    if(fs.existsSync(full)&&fs.existsSync(small)){
      const fullMeta=await sharp(full).metadata(), smallMeta=await sharp(small).metadata();
      if(fullMeta.width!==768 || fullMeta.height!==1097 || smallMeta.width!==512) failures.push(`${row.id}: wrong delivery dimensions`);
      if(fs.statSync(small).size>=fs.statSync(full).size) failures.push(`${row.id}: thumbnail is not smaller`);
      if(digests.has(row.runtimeSha256))failures.push(`${row.id}: duplicate illustration of ${digests.get(row.runtimeSha256)}`);
      digests.set(row.runtimeSha256,row.id);
    }
    if(row.needsFigures && (!row.figures?.front || !row.figures?.back)) failures.push(`${row.id}: matching figures pending`);
    if(row.figures?.front&&row.figures?.back&&(
      row.figureVisualReview?.result!=='accepted'||row.figureVisualReview.frontSha256!==row.figures.front.sha256||row.figureVisualReview.backSha256!==row.figures.back.sha256
    )) failures.push(`${row.id}: matching figure visual review pending`);
    for(const direction of ['front','back']){
      const figure=row.figures?.[direction];if(!figure)continue;
      const output=path.join(publicDir,figure.runtimePath), master=path.join(root,figure.masterPath);
      if(!fs.existsSync(output)||hash(output)!==figure.sha256||!fs.existsSync(master)||hash(master)!==figure.masterSha256){failures.push(`${row.id}: invalid ${direction} figure`);continue;}
      const stats=await sharp(output).stats(),meta=await sharp(output).metadata();
      if(!meta.hasAlpha||stats.channels[3]?.min!==0)failures.push(`${row.id}: ${direction} figure has no transparency`);
    }
  }
  console.log(JSON.stringify({total:data.cards.length,packaged:data.cards.filter(r=>r.status==='packaged').length,failures},null,2));
  if(failures.length) process.exitCode=1;
}
function summary() {
  const data=readManifest();
  const done=data.cards.filter(row=>row.status==='packaged');
  const figureCards=data.cards.filter(row=>row.needsFigures);
  const pairs=figureCards.filter(row=>row.status==='packaged'&&row.figures?.front&&row.figures?.back);
  const reviewed=done.filter(row=>row.visualReview?.result==='accepted'&&Boolean(row.runtimeSha256)&&row.visualReview.runtimeSha256===row.runtimeSha256);
  console.log(JSON.stringify({faces:{total:data.cards.length,packaged:done.length,visuallyReviewed:reviewed.length,remaining:data.cards.length-done.length},figurePairs:{total:figureCards.length,packaged:pairs.length,remaining:figureCards.length-pairs.length}},null,2));
}
const [command,id,source,figureSource]=process.argv.slice(2);
Promise.resolve(command === 'inventory' ? inventory() : command === 'summary' ? summary() : command === 'accept' ? accept(id,source) : command === 'accept-figure' ? acceptFigure(id,source,figureSource) : command === 'reject' ? reject(id,source) : command === 'contacts' ? contacts(id) : command === 'audit' ? audit() : (()=>{throw Error('Use inventory, summary, accept <id> <source>, accept-figure <id> <front|back> <source>, reject <id> <reason>, contacts [original|pilot|new], audit');})()).catch(error=>{console.error(error);process.exitCode=1;});
