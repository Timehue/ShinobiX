/** Keep every packaged ID in order while avoiding repeated URL prefixes in the
 * browser bundle. Unusual future paths retain the literal registry verbatim. */
function chronicleArtRegistrySource(art, figures) {
  const ids = Object.keys(art), figureIds = Object.keys(figures);
  const cards = ids.length && ids.every(id => !/\s/.test(id) && art[id] === `/chronicle/cards/${id}-painted-v2.webp`)
    ? `Object.fromEntries(${JSON.stringify(ids.join(' '))}.split(' ').map(id => [id, \`/chronicle/cards/\${id}-painted-v2.webp\`]))`
    : JSON.stringify(art, null, 2);
  const bodies = figureIds.length && figureIds.every(id => !/\s/.test(id) && figures[id].front === `/chronicle/figures/${id}-painted-v2.webp` && figures[id].back === `/chronicle/figures/${id}-painted-v2-back.webp`)
    ? `Object.fromEntries(${JSON.stringify(figureIds.join(' '))}.split(' ').map(id => [id, {front: \`/chronicle/figures/\${id}-painted-v2.webp\`, back: \`/chronicle/figures/\${id}-painted-v2-back.webp\`}]))`
    : JSON.stringify(figures, null, 2);
  return '// Generated by scripts/chronicle-art-production.cjs from packaged, verified assets.\n'
    + `export const CHRONICLE_PAINTED_ART: Readonly<Record<string, string>> = Object.freeze(${cards});\n\n`
    + `export const CHRONICLE_PAINTED_FIGURES: Readonly<Record<string, { front: string; back: string }>> = Object.freeze(${bodies});\n`;
}
module.exports = { chronicleArtRegistrySource };
