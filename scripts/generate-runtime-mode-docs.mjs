import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
    INTENTIONAL_ENGINE_SEPARATIONS,
    RUNTIME_AUTHORITY_ENGINES,
    RUNTIME_MODE_REGISTRY,
    RUNTIME_ORCHESTRATORS,
} from '../shared/runtime-mode-registry.ts';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repoRoot, 'docs', 'generated', 'runtime-mode-registry.md');

function textCell(value) {
    if (value == null || value === '') return '—';
    return String(value)
        .replaceAll('&', '&amp;')
        .replaceAll('|', '&#124;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('\r', '')
        .replaceAll('\n', '<br>');
}

function codeCell(value) {
    if (value == null || value === '') return '—';
    return `<code>${textCell(value).replaceAll('`', '&#96;')}</code>`;
}

function listCell(values) {
    return values.length > 0 ? values.map(codeCell).join('<br>') : '—';
}

function routeCell(routes) {
    if (routes.length === 0) return '—';
    return routes
        .map((route) => {
            const callerRequirement = route.clientCallerRequired === false ? 'server-internal' : 'client caller required';
            return `${codeCell(route.roles.join(', '))} ${codeCell(route.path)} → ${codeCell(route.handler)} (${callerRequirement})`;
        })
        .join('<br>');
}

function transportCell(transports = []) {
    if (transports.length === 0) return '—';
    return transports
        .map((transport) => (
            `${codeCell(transport.roles.join(', '))} ${codeCell(transport.kind)} ${codeCell(transport.channel)}`
            + ` → ${codeCell(transport.serverHandler)} / ${codeCell(transport.clientAdapter)}`
            + ` (${textCell(transport.persistence)})`
        ))
        .join('<br>');
}

/**
 * Render the human-readable registry projection without reading the clock,
 * filesystem, environment, or process state. Registry order is preserved.
 */
export function renderRuntimeModeDocs({
    modes = RUNTIME_MODE_REGISTRY,
    engines = RUNTIME_AUTHORITY_ENGINES,
    orchestrators = RUNTIME_ORCHESTRATORS,
    separations = INTENTIONAL_ENGINE_SEPARATIONS,
} = {}) {
    const lines = [
        '# Runtime Mode Registry',
        '',
        '> [!IMPORTANT]',
        '> This file is generated by [`scripts/generate-runtime-mode-docs.mjs`](../../scripts/generate-runtime-mode-docs.mjs)',
        '> from [`shared/runtime-mode-registry.ts`](../../shared/runtime-mode-registry.ts). Do not edit it by hand.',
        '> Run `npm run generate:runtime-mode-docs` after changing the registry and',
        '> `npm run check:runtime-mode-docs` to detect drift.',
        '',
        '`authorityEngine` is the runtime mounted today. `intendedAuthorityEngine` appears only when the verified owner differs or a missing surface already has a selected family. Status details record known gaps and defects; they are not production-readiness claims.',
        '',
        'A `capabilityKey` is only a binding to the public capability projection. It does not mean the mode is enabled, disabled, or healthy. Current availability remains owned by [`shared/public-capabilities.ts`](../../shared/public-capabilities.ts), its server implementation, and [`docs/LIVE_PRODUCT_STATUS.md`](../LIVE_PRODUCT_STATUS.md).',
        '',
        'Legacy `migrationStatus` and `compatibility` metadata support the retired migration-oriented projection. They are intentionally omitted from this current authority view.',
        '',
        '## Mode authority',
        '',
        '| Mode | Category | Mounted owner | Intended owner | Participants | Reward | Record / replay | Orchestrator | Capability | Status |',
        '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
        ...modes.map((mode) => [
            `${codeCell(mode.id)}<br>${textCell(mode.label)}`,
            codeCell(mode.category),
            codeCell(mode.authorityEngine),
            codeCell(mode.intendedAuthorityEngine),
            codeCell(mode.participantModel),
            codeCell(mode.rewardPolicy),
            codeCell(mode.replayKind),
            codeCell(mode.orchestrationOwner),
            codeCell(mode.capabilityKey),
            codeCell(mode.status),
        ].join(' | ').replace(/^/, '| ').replace(/$/, ' |')),
        '',
        '## Routes, transports, and client entries',
        '',
        'HTTP route roles, paths, handlers, and non-HTTP gameplay transports are reproduced exactly as declared by the registry. Client entries and transport adapters are relative to `shinobij.client/src/`; transport handlers are relative to `api/`.',
        '',
        '| Mode | HTTP route roles, paths, handlers, and caller requirement | Non-HTTP transport | Client entries |',
        '| --- | --- | --- | --- |',
        ...modes.map((mode) => `| ${codeCell(mode.id)} | ${routeCell(mode.routes)} | ${transportCell(mode.transports)} | ${listCell(mode.clientEntries)} |`),
        '',
        '## Intentional engine separations',
        '',
        'These relationships prevent a shared rule or adapter from being mistaken for permission to merge product runtimes.',
        '',
        '| Engine | Intentionally separate from |',
        '| --- | --- |',
        ...Object.values(engines).map((engine) => `| ${codeCell(engine)} | ${listCell(separations[engine] ?? [])} |`),
        '',
        '## Declared orchestration owners',
        '',
        'Orchestrators admit, coordinate, or settle a mode; they are not combat engines.',
        '',
        '| Orchestrator | Modes |',
        '| --- | --- |',
        ...Object.values(orchestrators).map((orchestrator) => {
            const ownedModes = modes.filter((mode) => mode.orchestrationOwner === orchestrator).map((mode) => mode.id);
            return `| ${codeCell(orchestrator)} | ${listCell(ownedModes)} |`;
        }),
        '',
        '## Open gaps and mismatches',
        '',
        '| Mode | Status | Mounted owner | Intended owner | Detail |',
        '| --- | --- | --- | --- | --- |',
        ...modes
            .filter((mode) => mode.status !== 'match')
            .map((mode) => `| ${codeCell(mode.id)} | ${codeCell(mode.status)} | ${codeCell(mode.authorityEngine)} | ${codeCell(mode.intendedAuthorityEngine)} | ${textCell(mode.statusDetail)} |`),
        '',
        '## Public capability bindings',
        '',
        'Only explicit bindings are listed. An unlisted mode has no registry binding; that absence is not an availability statement.',
        '',
        '| Mode | Capability key |',
        '| --- | --- |',
        ...modes
            .filter((mode) => mode.capabilityKey != null)
            .map((mode) => `| ${codeCell(mode.id)} | ${codeCell(mode.capabilityKey)} |`),
        '',
    ];

    return lines.join('\n');
}

async function writeOrCheck({ checkOnly }) {
    const content = renderRuntimeModeDocs();
    const relativeOutput = path.relative(repoRoot, outputPath).replaceAll('\\', '/');

    if (checkOnly) {
        const current = await readFile(outputPath, 'utf8')
            .then((value) => value.replace(/\r\n/g, '\n'))
            .catch(() => null);
        if (current !== content) {
            throw new Error(`${relativeOutput} is stale or missing; run npm run generate:runtime-mode-docs`);
        }
        console.error(`[runtime-mode-docs] ${relativeOutput} is current`);
        return;
    }

    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, content, 'utf8');
    console.error(`[runtime-mode-docs] wrote ${relativeOutput}`);
}

async function main() {
    const args = process.argv.slice(2);
    const unknownArgs = args.filter((arg) => arg !== '--check');
    if (unknownArgs.length > 0) throw new Error(`Unknown argument(s): ${unknownArgs.join(', ')}`);
    await writeOrCheck({ checkOnly: args.includes('--check') });
}

const invokedPath = process.argv[1] == null ? null : pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedPath === import.meta.url) await main();
